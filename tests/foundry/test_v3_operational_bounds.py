@pytest.fixture()
def db(tmp_path):
    database = FoundryDatabase(tmp_path / "db.sqlite")
    database.initialize()
    return database


REPO_ROOT = Path(__file__).resolve().parents[2]
FIXTURE_PATH = (REPO_ROOT / "ui" / "command-center" / "src" / "lib"
                / "__fixtures__" / "discoveryBackendFixture.gen.ts")


def _extract_fixture_payload() -> dict:
    """Parse the generated TS fixture back to its JSON object."""
    assert FIXTURE_PATH.exists(), (
        f"{FIXTURE_PATH} missing — run scripts/v3_operational_e2e.py to "
        "generate the backend contract fixture")
    text = FIXTURE_PATH.read_text(encoding="utf-8")
    match = re.search(r"backendDiscoveryPayload = (\{.*?\}) as const;",
                      text, re.DOTALL)
    assert match, "generated fixture lost its payload block"
    raw = match.group(1)
    # The generator emits plain json.dumps output — parse directly.
    return json.loads(raw)


def test_generated_fixture_matches_backend_projection_shape(db):
    """Drift detection: the fixture's shape must remain mapper-compatible.

    If the backend projection changes field names/types without regenerating
    the fixture (or vice versa), this fails.
    """
    payload = _extract_fixture_payload()

    required_top = {
        "schema", "state", "flag_state", "policy_version", "latest_cycle",
        "cycles", "candidates_recent", "selected", "portfolio_summary",
        "active_team", "verifier", "outcomes", "maintenance_due",
        "next_action",
    }
    missing = required_top - set(payload)
    assert not missing, f"fixture drifted: missing {missing}"

    if payload["candidates_recent"]:
        cand = payload["candidates_recent"][0]
        for key in ("candidate_id", "objective", "status", "score",
                    "rejection", "superseded_by", "deferred_until",
                    "evidence_ref_count", "mission_id", "partial"):
            assert key in cand, f"candidate shape drifted: no {key}"
        if cand["score"] is not None:
            for key in ("total", "policy_version", "dimensions",
                        "calibration_adjust", "thresholds"):
                assert key in cand["score"], f"score shape drifted: {key}"

    if payload["latest_cycle"] is not None:
        cycle = payload["latest_cycle"]
        for key in ("loop_id", "started_at", "completed_at", "outcome",
                    "decision_id", "mission_id", "observed",
                    "candidates_created", "scored", "eligible", "rejected",
                    "degraded_sources", "reason", "wait_kind"):
            assert key in cycle, f"cycle shape drifted: {key}"

    # cost_window must NEVER appear (unfabricated by contract).
    assert "cost_window" not in payload


def test_high_cardinality_ledger_bounded_latency_and_payload(db):
    """Many candidates/cycles/events: projection stays bounded and fast."""
    register_policy(db, {
        "policy_version": "v3-policy-bench",
        "weights": {dimension: 1.0 if dimension == "strategic_fit" else 0.0
                    for dimension in DIMENSIONS},
        "thresholds": {
            "min_total_score": 0.40,
            "min_strategic_fit": 0.0,
            "min_confidence": 0.0,
            "min_information_gain_for_research_override": 0.0,
            "comparative_wait_margin": 0.0,
        },
        "hard_filters": {"max_blast_radius": 0.85, "min_evidence_refs": 0},
    })
    now = "2026-08-22T10:00:00Z"
    with db.connect() as connection:
        for i in range(300):
            connection.execute(
                "INSERT INTO candidates (candidate_id, mission_id, source,"
                " objective, objective_canonical, evidence_json, status,"
                " fingerprint, candidate_type, expected_outcome,"
                " last_event_id, updated_at)"
                " VALUES (?, 'm', 'bench', ?, ?, '[]', 'NEW', ?, 'repair',"
                " 'x', ?, ?)",
                (f"cand-{i:04d}", f"objective number {i}", f"obj {i}",
                 f"fp-{i}", f"s:{i}", now))
            if i % 5 == 0:
                connection.execute(
                    "INSERT OR REPLACE INTO candidate_scores (candidate_id,"
                    " score, weights_json, last_event_id, updated_at)"
                    " VALUES (?, 0.5, '{}', ?, ?)",
                    (f"cand-{i:04d}", f"sc:{i}", now))
        for i in range(200):
            connection.execute(
                "INSERT INTO events (event_id, event_type, occurred_at,"
                " recorded_at, source_type, source_id, correlation_id,"
                " idempotency_key, schema_version, payload_json,"
                " payload_hash)"
                " VALUES (?, 'discovery.cycle_completed', ?, ?, 'supervisor',"
                " 'bench', '', ?, 36, ?, ?)",
                (f"evt-cyc-{i:04d}", now, now,
                 f"discovery.cycle_completed:L-{i:04d}",
                 json.dumps({"loop_id": f"L-{i:04d}", "outcome": "WAITING",
                             "observed": i, "candidates_created": 0,
                             "decision_id": None, "degraded_sources": [],
                             "reason": "r"}),
                 f"{i:04d}" * 16))
        for i in range(150):
            connection.execute(
                "INSERT INTO candidate_outcomes (outcome_id, candidate_id,"
                " mission_id, window_kind, predicted_value_json,"
                " actual_value_json, status, confidence, last_event_id,"
                " updated_at)"
                " VALUES (?, ?, ?, 'immediate', '{}', '{}', 'UNKNOWN', 0.0,"
                " ?, ?)",
                (f"cand-{i:04d}:immediate", f"cand-{i:04d}", f"M-{i:04d}",
                 f"o:{i}", now))

    start = time.perf_counter()
    snapshot = build_snapshot(db)
    elapsed = time.perf_counter() - start
    discovery = snapshot["discovery"]

    payload_bytes = len(json.dumps(snapshot).encode("utf-8"))

    assert len(discovery["candidates_recent"]) <= DISCOVERY_MAX_CANDIDATES
    assert len(discovery["cycles"]) <= DISCOVERY_MAX_CYCLES
    assert len(discovery["outcomes"]) <= 50
    assert discovery["cycles"][0]["loop_id"] == "L-0199"   # newest first
    # Bound: existing Command Center conventions bound timeline at 200
    # events / ~100-row tables; discovery adds well under one megabyte and
    # builds fast enough for a 5s poll loop even at this cardinality.
    assert elapsed < 2.0, f"projection too slow on synthetic ledger: {elapsed:.3f}s"
    assert payload_bytes < 1_500_000, (
        f"snapshot payload unbounded: {payload_bytes} bytes")

    print(f"\n[bench] candidates=300 cycles=200 outcomes=150 -> "
          f"{elapsed*1000:.1f}ms, discovery+full snapshot "
          f"{payload_bytes/1024:.0f} KiB")


def test_snapshot_json_safe_with_hostile_text(db):
    """SQL/control-char text is data: serialized safely, table survives."""
    hostile = ("x'); DROP TABLE candidates; --\n\x00\x1f<script>alert(1)"
               "</script>\u2028\ufeff")
    with db.connect() as connection:
        connection.execute(
            "INSERT INTO candidates (candidate_id, mission_id, source,"
            " objective, objective_canonical, evidence_json, status,"
            " last_event_id, updated_at)"
            " VALUES ('cand-hostile', 'm', 'test', ?, ?, '[]', 'NEW',"
            " 'e', '2026-08-22T10:00:00Z')",
            (hostile, hostile))
    snapshot = build_snapshot(db)
    serialized = json.dumps(snapshot, ensure_ascii=True)
    assert "DROP TABLE candidates" in serialized  # carried verbatim as data
    with db.connect() as connection:
        count = connection.execute(
            "SELECT COUNT(*) FROM candidates").fetchone()[0]
    assert count == 1  # table intact — parameterized reads throughout
