export function readStoredLocale(): UiLocale {
  try {
    const value = window.localStorage.getItem(LOCALE_STORAGE_KEY)
    return value === "sq" ? "sq" : "en"
  } catch {
    return "en"
  }
}

export function readStoredRouting(): NotificationRouting {
  try {
    const value = window.localStorage.getItem(NOTIFY_STORAGE_KEY)
    if (value === "off" || value === "in-app" || value === "in-app-toast") return value
  } catch {
    /* ignore */
  }
  return "in-app-toast"
}
